/**
 * Native, project-scoped Claude Ads skill trees for Claude Code and Codex, copied byte-for-byte from the verified
 * vendored assets. Layout per target (relative to the session workspace):
 *
 *   claude  .claude/skills/{ads,ads-*,hapi-ads}/…  and  .claude/agents/<upstream agent>.md
 *   codex   .agents/skills/{ads,ads-*,hapi-ads}/…
 *
 * `ads/` mirrors the upstream source layout its SKILL.md refers to: `references/`, `agents/openai.yaml`, the public
 * runtime resources under `control-plane/` and the JSON schemas under `claude_ads_core/schemas/v1/`. No Python code,
 * installer or helper script is copied.
 *
 * Trust model (first release): only the bytes shipped in this HAPI release count. A missing file is created
 * exclusively; an existing file whose bytes equal the shipped file is adopted unchanged; any other existing file is a
 * conflict and stays untouched. Nothing is ever replaced or deleted: project files (including a previous
 * `.hapi-claude-ads.json`) are not trusted evidence of ownership. The record `.hapi-claude-ads.json` in each skills
 * directory is itself a shipped, deterministic file (paths and digests of this release) and follows the same rules.
 * All requested targets are planned before any write; a conflict in any of them aborts the whole call unchanged.
 * Symlinks are never followed. This does not defend against a hostile process of the same user racing directory
 * components during the call.
 */
import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { CLAUDE_ADS_BUNDLED_PLUGIN_ID, CLAUDE_ADS_UPSTREAM } from '@hapi/protocol/bundledPlugins'
import { CLAUDE_ADS_PROVENANCE_SHA256 } from './assets.generated'
import type { AdsAssets } from './assets'
import { fail, readInput, statBelow, writeNew } from './files'
import { join } from 'node:path'

export const ADS_SKILL_TARGETS = ['claude', 'codex'] as const
export type AdsSkillTarget = typeof ADS_SKILL_TARGETS[number]
export const ADS_TARGET_LAYOUT: Record<AdsSkillTarget, { skills: string; agents: string | null }> = {
    claude: { skills: '.claude/skills', agents: '.claude/agents' },
    codex: { skills: '.agents/skills', agents: null },
}
export const ADS_OWNERSHIP_FILE = '.hapi-claude-ads.json'

/** `source` = vendored file to copy; `data` = generated bytes (the ownership record). */
type PlannedFile = { path: string; sha256: string; bytes: number } & ({ source: string; data?: undefined } | { data: string; source?: undefined })
export type AdsOwnership = { schemaVersion: 1; pluginId: string; target: AdsSkillTarget; upstreamCommit: string; provenanceSha256: string; files: Array<{ path: string; sha256: string }> }
export type AdsSkillPlan = {
    target: AdsSkillTarget; workspace: string; skillsDirectory: string
    create: string[]; unchanged: string[]
    conflicts: Array<{ path: string; reason: string }>
}
export type AdsSkillState = 'installed' | 'incomplete' | 'not_installed' | 'conflict'

const sha256 = (data: Uint8Array) => createHash('sha256').update(data).digest('hex')

/** Files of one target (paths relative to the workspace), derived only from the verified provenance list. */
export function adsSkillFiles(assets: AdsAssets, target: AdsSkillTarget): PlannedFile[] {
    const layout = ADS_TARGET_LAYOUT[target], files: PlannedFile[] = []
    const add = (path: string, source: string, digest: string, bytes: number) => files.push({ path, source, sha256: digest, bytes })
    for (const file of assets.files) {
        const source = join(assets.upstream, file.path)
        let match: RegExpExecArray | null
        if (file.path === 'ads/SKILL.md' || /^ads\/(references\/[a-z0-9-]+\.md|agents\/[a-z0-9-]+\.yaml)$/.test(file.path)) add(`${layout.skills}/${file.path}`, source, file.sha256, file.bytes)
        else if (/^control-plane\/(manifests|schemas)\/[a-z0-9.-]+\.json$/.test(file.path) || /^control-plane\/[A-Z_]+\.md$/.test(file.path)) add(`${layout.skills}/ads/${file.path}`, source, file.sha256, file.bytes)
        else if (/^claude_ads_core\/schemas\/v1\/[a-z0-9.-]+\.json$/.test(file.path)) add(`${layout.skills}/ads/${file.path}`, source, file.sha256, file.bytes)
        else if ((match = /^skills\/(ads-[a-z0-9-]+\/(?:SKILL\.md|assets\/[a-z0-9-]+\.md))$/.exec(file.path))) add(`${layout.skills}/${match[1]}`, source, file.sha256, file.bytes)
        else if (layout.agents && (match = /^agents\/([a-z0-9-]+\.md)$/.exec(file.path))) add(`${layout.agents}/${match[1]}`, source, file.sha256, file.bytes)
    }
    for (const [path, digest] of Object.entries(assets.adapter)) {
        const name = /^hapi\/(hapi-ads\/SKILL\.md)$/.exec(path)?.[1]
        if (name) add(`${layout.skills}/${name}`, join(assets.root, path), digest, readFileSync(join(assets.root, path)).byteLength)
    }
    return files.sort((a, b) => a.path.localeCompare(b.path))
}

/** Deterministic ownership record of this release for one target (shipped bytes, not read back as evidence). */
export function adsOwnershipRecord(assets: AdsAssets, target: AdsSkillTarget): PlannedFile {
    const record: AdsOwnership = { schemaVersion: 1, pluginId: CLAUDE_ADS_BUNDLED_PLUGIN_ID, target, upstreamCommit: CLAUDE_ADS_UPSTREAM.commit, provenanceSha256: CLAUDE_ADS_PROVENANCE_SHA256,
        files: adsSkillFiles(assets, target).map(file => ({ path: file.path, sha256: file.sha256 })) }
    const data = `${JSON.stringify(record, null, 2)}\n`
    return { path: `${ADS_TARGET_LAYOUT[target].skills}/${ADS_OWNERSHIP_FILE}`, data, sha256: sha256(Buffer.from(data)), bytes: Buffer.byteLength(data) }
}
function plannedFiles(assets: AdsAssets, target: AdsSkillTarget): PlannedFile[] { return [...adsSkillFiles(assets, target), adsOwnershipRecord(assets, target)] }

/**
 * Digest of an existing regular file below the workspace (null when absent; 'differs' without reading when its size is
 * not the shipped size). Reads go through the pinned file boundary, bounded by the shipped length.
 */
function currentDigest(workspace: string, rel: string, expectedBytes: number): string | 'differs' | null {
    const stat = statBelow(workspace, rel)
    if (stat.kind === 'missing') return null
    if (stat.kind !== 'file') fail(`Not a regular file: ${rel}`)
    if (stat.size !== expectedBytes) return 'differs'
    return sha256(readInput(workspace, rel, expectedBytes))
}

/** Read-only comparison of the shipped file set with the workspace. */
export function planAdsSkills(assets: AdsAssets, workspace: string, target: AdsSkillTarget): AdsSkillPlan {
    const plan: AdsSkillPlan = { target, workspace, skillsDirectory: join(workspace, ADS_TARGET_LAYOUT[target].skills), create: [], unchanged: [], conflicts: [] }
    for (const file of plannedFiles(assets, target)) {
        let digest: string | null
        try { digest = currentDigest(workspace, file.path, file.bytes) } catch (error) { plan.conflicts.push({ path: file.path, reason: (error as Error).message }); continue }
        if (digest === null) plan.create.push(file.path)
        else if (digest === file.sha256) plan.unchanged.push(file.path)
        else plan.conflicts.push({ path: file.path, reason: 'An existing file differs from the shipped file; it is left unchanged' })
    }
    return plan
}

export function adsSkillState(plan: AdsSkillPlan): AdsSkillState {
    if (plan.conflicts.length) return 'conflict'
    if (!plan.create.length) return 'installed'
    return plan.unchanged.length ? 'incomplete' : 'not_installed'
}

/**
 * Plans every requested target first; with any conflict nothing is written. Then creates only missing files, each
 * exclusively (a file that appears meanwhile is never replaced and stops the call). The ownership record comes last.
 */
export function installAdsSkills(assets: AdsAssets, workspace: string, requested: AdsSkillTarget | readonly AdsSkillTarget[]): { applied: boolean; plans: AdsSkillPlan[]; conflicts: AdsSkillPlan['conflicts'] } {
    const plans = (typeof requested === 'string' ? [requested] : [...requested]).map(target => planAdsSkills(assets, workspace, target))
    const conflicts = plans.flatMap(plan => plan.conflicts)
    if (conflicts.length) return { applied: false, plans, conflicts }
    for (const plan of plans) {
        const byPath = new Map(plannedFiles(assets, plan.target).map(file => [file.path, file]))
        const ordered = [...plan.create].sort((a, b) => Number(a.endsWith(ADS_OWNERSHIP_FILE)) - Number(b.endsWith(ADS_OWNERSHIP_FILE)))
        for (const path of ordered) {
            const file = byPath.get(path)!
            const data = file.source !== undefined ? readFileSync(file.source) : Buffer.from(file.data!)
            if (sha256(data) !== file.sha256) fail(`Vendored file changed during installation: ${path}`)
            writeNew(workspace, path, data)
        }
    }
    return { applied: true, plans, conflicts }
}

/** Compact, user-facing summary of a plan (counts plus bounded path lists). */
export function summarizePlan(plan: AdsSkillPlan, applied: boolean) {
    return {
        target: plan.target, skillsDirectory: plan.skillsDirectory, applied, state: applied ? 'installed' : adsSkillState(plan),
        counts: { create: plan.create.length, unchanged: plan.unchanged.length, conflicts: plan.conflicts.length },
        conflicts: plan.conflicts.slice(0, 50), create: plan.create.slice(0, 20),
        invoke: plan.target === 'claude' ? 'Claude Code: /ads, /ads-audit, … (skills); agents in .claude/agents' : 'Codex: $ads, $ads-audit, … (skills in .agents/skills; upstream marks Codex support experimental)',
    }
}
